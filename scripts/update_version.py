"""
Update the GRIDGEN version in the files that hold it.

The version is read from version.txt unless --version is given. A version
containing "dev" is a development version: the program banner adds the git
commit and the release notes are in develop mode. --releasemode also updates
the README software citation and archives the release notes for the version.
"""

import argparse
import datetime
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NOTES_DIR = ROOT / "doc" / "ReleaseNotes"


def long_date(date):
    """January 6, 2017"""
    return f"{date:%B} {date.day}, {date.year}"


def replace(path, pattern, repl, count=1):
    """Substitute pattern in path; fail if it does not match."""
    text = path.read_text()
    new, n = re.subn(pattern, repl, text, count=count, flags=re.M)
    if n == 0:
        sys.exit(f"{path.relative_to(ROOT)}: no match for {pattern!r}")
    path.write_text(new)
    print(f"updated {path.relative_to(ROOT)}")


def update_version_txt(version):
    (ROOT / "version.txt").write_text(version + "\n")
    print("updated version.txt")


def update_meson_build(date):
    replace(
        ROOT / "meson.build",
        r"^release_date = '.*'$",
        f"release_date = '{long_date(date)}'",
    )


def update_pixi_toml(version):
    replace(ROOT / "pixi.toml", r'^version = ".*"$', f'version = "{version}"')


def update_version_tex(version, date, develop):
    path = NOTES_DIR / "version.tex"
    if not path.is_file():
        return
    path.write_text(
        f"\\newcommand{{\\gridgenversion}}{{{version}}}\n"
        f"\\newcommand{{\\gridgendate}}{{{long_date(date)}}}\n"
        "\\newif\\ifdevelopmode\n"
        f"\\developmode{'true' if develop else 'false'}\n"
    )
    print(f"updated {path.relative_to(ROOT)}")


# README software citation heading and text
README_HEADING = r"^### Software/Code Citation for GRIDGEN v.*$"
README_CITATION = (
    r"\d{4}, GRIDGEN version \S+ -- (.*) Software Release, \d{2} \w+ \d{4}\."
)


def update_readme(version, date):
    path = ROOT / "README.md"
    replace(path, README_HEADING, f"### Software/Code Citation for GRIDGEN v{version}")
    replace(
        path,
        README_CITATION,
        rf"{date.year}, GRIDGEN version {version} -- \1 Software Release, "
        f"{date:%d %B %Y}.",
    )


def archive_release_notes(version, date):
    """Keep the generated History entry in previous/ and remove the items."""
    if not (NOTES_DIR / "mk_releasenotes.py").is_file():
        return
    name = f"v{version}"
    archived = NOTES_DIR / "previous" / f"{name}.tex"
    if archived.is_file():
        print(f"release notes already archived as previous/{name}.tex")
        return
    subprocess.run([sys.executable, "mk_releasenotes.py"], cwd=NOTES_DIR, check=True)
    develop_tex = NOTES_DIR / "develop.tex"
    entry = develop_tex.read_text(encoding="utf-8")
    for old, new in (
        (
            r"\item Version \gridgenversion\ifdevelopmode\ (in development)\fi",
            rf"\item Version {version} {date.month}/{date.day}/{date.year}",
        ),
        (
            "% generated by mk_releasenotes.py from items/*.toml; do not edit",
            f"% release notes for GRIDGEN version {version}",
        ),
    ):
        if old not in entry:
            sys.exit(f"develop.tex: no match for {old!r}")
        entry = entry.replace(old, new)
    archived.write_text(entry, encoding="utf-8")
    develop_tex.unlink()
    for item in (NOTES_DIR / "items").glob("*.toml"):
        item.unlink()
    replace(
        NOTES_DIR / "ReleaseNotes.tex",
        r"^(  \\IfFileExists\{develop\.tex\}\{\\input\{develop\.tex\}\}\{\}\n)",
        rf"\1  \\input{{previous/{name}.tex}}\n",
    )
    print(f"archived the release notes as previous/{name}.tex")


def archived(version):
    """True if the release notes for version are already archived."""
    return (NOTES_DIR / "previous" / f"v{version}.tex").is_file()


def check_release(version):
    """Fail before changing anything if a release cannot be completed."""
    readme = (ROOT / "README.md").read_text()
    for pattern in (README_HEADING, README_CITATION):
        if not re.search(pattern, readme, flags=re.M):
            sys.exit(f"README.md: no match for {pattern!r}")
    if not (NOTES_DIR / "mk_releasenotes.py").is_file() or archived(version):
        return
    if not any((NOTES_DIR / "items").glob("*.toml")):
        sys.exit("no release note items in doc/ReleaseNotes/items to archive")


def main():
    parser = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    parser.add_argument("--version", help="version (default: version.txt)")
    parser.add_argument("--date", help="release date, YYYY-MM-DD (default: today)")
    parser.add_argument(
        "--releasemode",
        action="store_true",
        help="update the README citation and archive the release notes",
    )
    args = parser.parse_args()

    version = args.version or (ROOT / "version.txt").read_text().strip()
    date = (
        datetime.date.fromisoformat(args.date) if args.date else datetime.date.today()
    )
    develop = "dev" in version
    if args.releasemode and develop:
        parser.error(f"{version} is a development version; give a release version")

    # a release already archived keeps its dates
    released = args.releasemode and archived(version)
    if args.releasemode:
        check_release(version)
    update_version_txt(version)
    update_pixi_toml(version)
    if released:
        print(f"{version} is already released; release dates and README unchanged")
        return
    update_version_tex(version, date, develop)
    if args.releasemode:
        update_meson_build(date)
        update_readme(version, date)
        archive_release_notes(version, date)


if __name__ == "__main__":
    main()
