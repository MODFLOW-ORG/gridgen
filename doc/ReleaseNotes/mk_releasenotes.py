"""
Render the release note items in items/*.toml to develop.tex, and the known
issues in known-issues/*.toml to knownissues.tex.

Each item has a section, an optional subsection, and a description; valid
sections and subsections are defined in schema.toml. develop.tex is the
History entry for the release in progress. Each known issue has the number of
its GitHub issue and a description. ReleaseNotes.tex inputs both files.
"""

import re
import sys
import tomllib
from pathlib import Path

NOTES_DIR = Path(__file__).resolve().parent
ITEMS_DIR = NOTES_DIR / "items"
KNOWN_ISSUES_DIR = NOTES_DIR / "known-issues"

# characters that are special in LaTeX, in text and in `code`
LATEX_ESCAPES = {
    "\\": r"\textbackslash{}",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
    "&": r"\&",
    "%": r"\%",
    "#": r"\#",
    "_": r"\_",
    "$": r"\$",
}


def load_items(sections, subsections):
    """Return (path, item) pairs; raise ValueError listing every invalid item."""
    items, errors = [], []
    for path in sorted(ITEMS_DIR.glob("*.toml")):
        try:
            item = tomllib.loads(path.read_text(encoding="utf-8"))
        except tomllib.TOMLDecodeError as e:
            errors.append(f"{path.name}: invalid TOML: {e}")
            continue
        bad_type = False
        for key in ("section", "description", "subsection"):
            if key not in item:
                if key != "subsection":
                    errors.append(f"{path.name}: missing required key '{key}'")
            elif not isinstance(item[key], str):
                errors.append(f"{path.name}: '{key}' must be a string")
                bad_type = True
        if bad_type:
            continue
        if item.get("section") not in sections:
            errors.append(f"{path.name}: invalid section '{item.get('section')}'")
        if item.get("subsection") and item["subsection"] not in subsections:
            errors.append(f"{path.name}: invalid subsection '{item['subsection']}'")
        items.append((path, item))
    if errors:
        raise ValueError("invalid release note items:\n" + "\n".join(errors))
    return items


def load_known_issues():
    """Return the known issues by number; raise ValueError listing invalid ones."""
    issues, errors = {}, []
    for path in sorted(KNOWN_ISSUES_DIR.glob("*.toml")):
        try:
            entry = tomllib.loads(path.read_text(encoding="utf-8"))
        except tomllib.TOMLDecodeError as e:
            errors.append(f"{path.name}: invalid TOML: {e}")
            continue
        number, description = entry.get("issue"), entry.get("description")
        unknown = sorted(set(entry) - {"issue", "description"})
        if unknown:
            errors.append(f"{path.name}: unknown keys {', '.join(unknown)}")
        # bool is an int in Python, but not an issue number
        if not isinstance(number, int) or isinstance(number, bool) or number < 1:
            errors.append(f"{path.name}: 'issue' must be a GitHub issue number")
            continue
        if not isinstance(description, str) or not description.strip():
            errors.append(f"{path.name}: 'description' must be a nonempty string")
            continue
        if number in issues:
            errors.append(f"{path.name}: issue {number} is also {issues[number][0]}")
            continue
        issues[number] = (path.name, description.strip())
    if errors:
        raise ValueError("invalid known issues:\n" + "\n".join(errors))
    return {number: description for number, (_, description) in issues.items()}


def to_latex(text):
    """Escape special characters and set `code` in typewriter type."""
    parts = re.split(r"(`[^`]*`)", text)
    out = []
    for part in parts:
        is_code = part.startswith("`") and part.endswith("`") and len(part) > 1
        if is_code:
            part = part[1:-1]
        part = "".join(LATEX_ESCAPES.get(c, c) for c in part)
        if not is_code:
            # straight double quotes as opening and closing quotes
            part = re.sub(r'"([^"]*)"', r"``\1''", part)
        out.append(r"\texttt{" + part + "}" if is_code else part)
    return "".join(out)


def render(sections, subsections, items):
    """History entry for the release in progress, grouped by section."""
    order = {name: i for i, name in enumerate(subsections)}
    lines = [
        "% generated by mk_releasenotes.py from items/*.toml; do not edit",
        r"\item Version \gridgenversion\ifdevelopmode\ (in development)\fi",
        r"\begin{itemize}[label=--]",
    ]
    for section, title in sections.items():
        chosen = [it for _, it in items if it["section"] == section]
        if not chosen:
            continue
        chosen.sort(key=lambda it: order.get(it.get("subsection", ""), -1))
        lines.append(rf"  \item[] \textbf{{{title}}}")
        for it in chosen:
            lines.append(r"  \item " + to_latex(it["description"].strip()))
    lines.append(r"\end{itemize}")
    return "\n".join(lines) + "\n"


def render_known_issues(issues):
    """Known Issues section, in the order of the issue numbers."""
    lines = ["% generated by mk_releasenotes.py from known-issues/*.toml; do not edit"]
    if not issues:
        lines.append("No defects are known in this version.")
        return "\n".join(lines) + "\n"
    lines += [
        "The following defects are known in this version. Each is tracked as an "
        "issue on GitHub (\\url{https://github.com/MODFLOW-ORG/gridgen/issues}) "
        "and is removed from this list when it is fixed.",
        "",
        r"\begin{itemize}",
    ]
    for number in sorted(issues):
        description = to_latex(issues[number]).removesuffix(".")
        lines.append(rf"  \item {description} (\ghissue{{{number}}}).")
    lines.append(r"\end{itemize}")
    return "\n".join(lines) + "\n"


def main():
    schema = tomllib.loads((NOTES_DIR / "schema.toml").read_text(encoding="utf-8"))
    sections, subsections = schema["sections"], schema.get("subsections", {})
    items = load_items(sections, subsections)
    issues = load_known_issues()
    tex = NOTES_DIR / "develop.tex"
    if items:
        tex.write_text(render(sections, subsections, items), encoding="utf-8")
        print(f"wrote {tex.name} from {len(items)} items")
    else:
        tex.unlink(missing_ok=True)
        print("no release note items")
    known = NOTES_DIR / "knownissues.tex"
    known.write_text(render_known_issues(issues), encoding="utf-8")
    print(f"wrote {known.name} from {len(issues)} known issues")


if __name__ == "__main__":
    try:
        main()
    except ValueError as e:
        sys.exit(str(e))
